/**
 * Port supabase/migrations/*.sql → neon/migrations/*.sql
 * - Keeps auth.users references (backed by view from 000_bootstrap_users.sql)
 * - Comments out Supabase realtime publication helpers that Neon does not provide
 * - Strips storage.* bucket DDL (files move to Vercel Blob)
 * - Writes a dual-run checklist markdown
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const srcDir = path.join(root, "supabase", "migrations");
const destDir = path.join(root, "neon", "migrations");

fs.mkdirSync(destDir, { recursive: true });

const files = fs
  .readdirSync(srcDir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const notes = [];

for (const file of files) {
  const raw = fs.readFileSync(path.join(srcDir, file), "utf8");
  let next = raw;

  // Storage bucket management is Supabase-only → Blob
  next = next.replace(
    /insert into storage\.buckets[\s\S]*?;/gi,
    "-- [neon-port] skipped storage.buckets insert (use Vercel Blob)\n"
  );
  next = next.replace(
    /create policy[\s\S]*?on storage\.[^;]+;/gi,
    "-- [neon-port] skipped storage policy\n"
  );

  // Realtime publication is Supabase-specific
  next = next.replace(
    /alter publication supabase_realtime[\s\S]*?;/gi,
    "-- [neon-port] skipped supabase_realtime publication (use Ably)\n"
  );

  // Soften auth schema grants that may fail on Neon
  next = next.replace(
    /grant usage on schema auth[\s\S]*?;/gi,
    "-- [neon-port] skipped auth schema grant\n"
  );

  const header = `-- Auto-ported from supabase/migrations/${file} for Neon
-- Review RLS: Neon API uses service DATABASE_URL; enforce auth in /api handlers.
-- Requires neon/migrations/000_bootstrap_users.sql first.

`;

  const outName = file;
  fs.writeFileSync(path.join(destDir, outName), header + next, "utf8");
  notes.push(`- [ ] Apply \`${outName}\``);
}

const checklist = `# Neon migration dual-run checklist

Generated by \`node scripts/port-migrations-to-neon.mjs\`.

## Apply order

1. Create a Neon project and copy the connection string to \`DATABASE_URL\`.
2. Run \`000_bootstrap_users.sql\`.
3. Run numbered migrations in order:

${notes.join("\n")}

## Dual-run validation

With both Supabase and Neon configured:

\`\`\`bash
curl -s "$VITE_APP_URL/api/platform/health" | jq
\`\`\`

Expect \`neon.ok: true\` and table counts when \`DUAL_RUN_VALIDATE=true\`.

## Cutover

1. Configure Clerk + Ably + Blob.
2. Set \`VITE_DATA_BACKEND=neon\`, \`VITE_AUTH_PROVIDER=clerk\`, \`VITE_REALTIME_PROVIDER=ably\`, \`VITE_STORAGE_PROVIDER=blob\`.
3. Sync users via Clerk webhook → \`app_users\` / \`profiles\`.
4. Decommission Supabase after freeze window.
`;

fs.writeFileSync(path.join(root, "neon", "DUAL_RUN.md"), checklist, "utf8");
console.log(`Ported ${files.length} migrations → neon/migrations`);
console.log("Wrote neon/DUAL_RUN.md");
